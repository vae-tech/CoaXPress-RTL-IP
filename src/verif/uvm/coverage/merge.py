"""Merge per-test coverage JSON dumps into one summary HTML page.

`make cov_report` invokes ``python3 -m uvm.coverage.merge cov_*.xml``.
We honour both .json (the format CovSubscriber emits) and .xml so the
regression script can pick either.

Output is straight HTML so the bin tally drops into the existing
tb_unit_test_report.html dashboard generated by tools/gen_test_report.py.
"""

from __future__ import annotations

import glob
import json
import sys
from collections import defaultdict


def main(argv):
    paths = []
    for p in argv:
        paths.extend(glob.glob(p))
    if not paths:
        # Fall back to whatever cov_summary.json is in the cwd.
        paths = glob.glob("cov_*.json") + glob.glob("cov_summary.json")

    totals = defaultdict(int)
    per_test = {}
    for p in paths:
        try:
            with open(p) as f:
                payload = json.load(f)
        except (OSError, json.JSONDecodeError):
            continue
        bins = payload.get("bins", {})
        per_test[payload.get("test", p)] = bins
        for k, v in bins.items():
            totals[k] += v

    print("<!doctype html><meta charset='utf-8'><title>CXP coverage</title>")
    print("<h1>CoaXPress IP coverage merge</h1>")
    print(f"<p>{len(per_test)} tests merged, {len(totals)} bins hit.</p>")
    print("<table border='1' cellpadding='4'>")
    print("<tr><th>Bin</th><th>Hits</th></tr>")
    for k in sorted(totals):
        print(f"<tr><td>{k}</td><td>{totals[k]}</td></tr>")
    print("</table>")


if __name__ == "__main__":
    main(sys.argv[1:])
