# =============================================================================
# Model
# =============================================================================
@dataclass
class Row:
    name: str
    addr: int
    kind: str
    nbytes: int = 4
    value: object = None
    reg: Optional[str] = None
    reset: int = 0
    conn_reset: Optional[int] = None
    maxv: Optional[int] = None
    max_links: bool = False            # max is p_NUM_LINKS - 1
    wr_pulse: Optional[str] = None
    out: Optional[str] = None
    bits: int = 32
    inp: Optional[str] = None
    nv: Optional[str] = None
    allowed: Optional[List[int]] = None
    minv: Optional[int] = None         # a write below this is refused
    multiple: Optional[int] = None     # a write must be a multiple of this (power of 2)
    entries: Optional[Dict[str, int]] = None  # `allowed` given as name -> value
    gc: Optional[dict] = None          # GenICam feature metadata; None = no feature


@dataclass
class Dev:
    name: str
    slot: int
    alias: int
    reg: str
    reset: int
    out: str
    allowed: Optional[List[int]] = None
    wr_pulse: Optional[str] = None     # output pulsed one cycle after every write
    reset_param: Optional[str] = None  # module parameter holding the power-on value
    minv: Optional[int] = None         # a write below this is refused
    maxv: Optional[int] = None         # a write above this is refused
    wo: bool = False                   # write-only: a read is refused (0x44)
    entries: Optional[Dict[str, int]] = None
    gc: Optional[dict] = None


@dataclass
class Mfr:
    name: str
    off: int
    reg: str
    out: Optional[str] = None
    reset: int = 0                     # power-on value
    minv: Optional[int] = None         # a write below this is refused
    maxv: Optional[int] = None         # a write above this is refused
    allowed: Optional[List[int]] = None
    entries: Optional[Dict[str, int]] = None
    gc: Optional[dict] = None


@dataclass
class Feat:
    """One GenICam feature and the register node behind it."""
    name: str
    type: str                          # Integer / Enumeration / Command / String / Boolean
    ns: str                            # NameSpace: Standard / Custom
    gc: dict
    addr: int
    length: int
    access: str                        # RO / RW / WO
    minv: Optional[int] = None
    maxv: Optional[int] = None
    inc: Optional[int] = None
    entries: Optional[Dict[str, int]] = None

    @property
    def reg(self) -> str:
        return f"{self.name}Reg"


@dataclass
class Map:
    module: str
    xml: dict
    mfr_base: int
    mfr_words: int
    rows: List[Row]
    dev: List[Dev]
    mfr: List[Mfr]
    gc: dict = None                    # the `genicam:` block
    xml_bytes: bytes = b""

    @property
    def blob_bytes(self) -> int:
        return len(self.xml_bytes)

    @property
    def blob_words(self) -> int:
        return (len(self.xml_bytes) + 3) // 4

    @property
    def xml_url(self) -> str:
        return f"Local:{self.xml['name']};{self.xml['blob_addr']:08X};{self.blob_bytes:X}"

    def kind(self, k: str) -> List[Row]:
        return [r for r in self.rows if r.kind == k]

    def one(self, k: str) -> Row:
        rows = self.kind(k)
        if len(rows) != 1:
            raise SystemExit(f"regmap: expected exactly one {k} row, found {len(rows)}")
        return rows[0]


def _version_word(v: dict) -> int:
    """§10.3.9-10: major << 16 | minor << 8 | sub-minor."""
    return (v["major"] << 16) | (v["minor"] << 8) | v.get("subminor", 0)


def _resolve(ns: dict, v):
    """`xml.<key>` / `genicam.<key>` in a row value names a computed value."""
    if isinstance(v, str) and "." in v and v.split(".", 1)[0] in ns:
        top, key = v.split(".", 1)
        return ns[top][key]
    return v


def _allowed(v):
    """`allowed` as (list of values, entry mapping or None)."""
    if isinstance(v, dict):
        return list(v.values()), dict(v)
    return v, None


def load() -> Map:
    with open(SRC) as f:
        y = yaml.safe_load(f)
    xml = dict(y["xml"])
    m = Map(module=y["module"], xml=xml, mfr_base=y["mfr"]["base"],
            mfr_words=y["mfr"]["words"], rows=[], dev=[], mfr=[], gc=dict(y["genicam"]))
    ns = {"xml": xml, "genicam": m.gc}
    for r in y["registers"]:
        if r["kind"] not in KINDS:
            raise SystemExit(f"{r['name']}: unknown kind {r['kind']}")
        allowed, entries = _allowed(r.get("allowed"))
        m.rows.append(Row(
            name=r["name"], addr=int(_resolve(ns, r["addr"])), kind=r["kind"],
            nbytes=r.get("len", 4), value=r.get("value"),
            reg=r.get("reg"), reset=r.get("reset", 0), conn_reset=r.get("conn_reset"),
            maxv=0 if r.get("max") == "links" else r.get("max"),
            max_links=r.get("max") == "links", wr_pulse=r.get("wr_pulse"),
            out=r.get("out"), bits=r.get("bits", 32), inp=r.get("in"), nv=r.get("nv"),
            allowed=allowed, minv=r.get("min"), multiple=r.get("multiple"),
            entries=entries, gc=r.get("gc")))
    for d in y["device"]:
        allowed, entries = _allowed(d.get("allowed"))
        m.dev.append(Dev(name=d["name"], slot=d["slot"], alias=d.get("alias", 0),
                         reg=d["reg"], reset=d["reset"], out=d["out"],
                         allowed=allowed, entries=entries, gc=d.get("gc"),
                         wr_pulse=d.get("wr_pulse"), reset_param=d.get("reset_param"),
                         minv=d.get("min"), maxv=d.get("max"), wo=d.get("access") == "WO"))
    for w in y["manufacturer"]:
        allowed, entries = _allowed(w.get("allowed"))
        m.mfr.append(Mfr(name=w["name"], off=w["offset"], reg=w["reg"], out=w.get("out"),
                         reset=w.get("reset", 0), minv=w.get("min"), maxv=w.get("max"),
                         allowed=allowed, entries=entries, gc=w.get("gc")))
    # The XML first; every value that depends on it comes from its bytes.
    text = gen_xml(m)
    m.xml_bytes = text.encode("utf-8")
    xml["version"] = _version_word(m.gc["version"])
    xml["schema_version"] = _version_word(m.gc["schema"])
    xml["url"] = m.xml_url
    for r in m.rows:
        r.value = _resolve(ns, r.value)
    _validate(m)
    _xml_selfcheck(m, text)
    return m


def _validate(m: Map) -> None:
    seen: Dict[int, str] = {}
    for r in m.rows:
        if r.addr & 3:
            raise SystemExit(f"{r.name}: address 0x{r.addr:X} not word-aligned")
        if r.addr > 0xFFFF:
            raise SystemExit(f"{r.name}: bootstrap rows decode 16 address bits")
        for w in range((r.nbytes + 3) // 4):
            a = r.addr + 4 * w
            if a in seen:
                raise SystemExit(f"{r.name}: 0x{a:04X} overlaps {seen[a]}")
            seen[a] = r.name
        # §10.3.28: the device executes a connection reset at power-up, so a
        # register with a ConnectionReset value powers up at that value.
        if r.conn_reset is not None and r.conn_reset != r.reset:
            raise SystemExit(f"{r.name}: reset 0x{r.reset:X} != conn_reset 0x{r.conn_reset:X} "
                             "(power-up executes a connection reset, §10.3.28)")
        if r.kind == "NVSTR" and (r.nbytes != 16 or r.addr & 0xF):
            raise SystemExit(f"{r.name}: NVSTR must be 16 bytes on a 16-byte boundary")
        if r.kind == "CNT" and not r.out:
            raise SystemExit(f"{r.name}: CNT needs `out`, its clear pulse")
        if r.kind == "STR" and len(str(r.value)) > r.nbytes:
            raise SystemExit(f"{r.name}: '{r.value}' longer than {r.nbytes} bytes")
        if r.allowed is not None and r.kind != "RW":
            raise SystemExit(f"{r.name}: `allowed` needs an RW row")
        if (r.maxv is not None or r.minv is not None or r.multiple) and r.kind not in ("RW", "CRST"):
            raise SystemExit(f"{r.name}: `min` / `max` / `multiple` need an RW or CRST row")
        if r.multiple and r.multiple & (r.multiple - 1):
            raise SystemExit(f"{r.name}: `multiple` must be a power of 2")
        if r.allowed is not None and r.reset not in r.allowed:
            raise SystemExit(f"{r.name}: power-on value not in `allowed`")
    for d in m.dev:
        if d.slot in seen:
            raise SystemExit(f"{d.name}: slot 0x{d.slot:04X} overlaps {seen[d.slot]}")
        if not (m.mfr_base <= d.alias < m.mfr_base + 4 * m.mfr_words):
            raise SystemExit(f"{d.name}: feature address 0x{d.alias:X} outside the manufacturer window")
    if m.mfr_words & (m.mfr_words - 1):
        raise SystemExit("mfr.words must be a power of two")
    offs = {w.off for w in m.mfr}
    for d in m.dev:
        if d.alias and d.alias - m.mfr_base in offs:
            raise SystemExit(f"{d.name}: alias overlaps a manufacturer word")
    if m.xml_url and len(m.xml_url) > 64:
        raise SystemExit("XmlUrl longer than its 64-byte field")


