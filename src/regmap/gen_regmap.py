def _cpp_opt(v: Optional[int]) -> str:
    return "NONE" if v is None else f"0x{v:X}"


def gen_hpp(m: Map) -> str:
    """The map for C++ (src/emu/host): constants and the row tables a
    reference device decodes with (the same data as regmodel.py)."""
    L = [f"// CoaXPress register map.  {BANNER}", "#pragma once", "",
         "#include <cstdint>", "", "namespace cxp::reg {", ""]
    a = L.append

    def c(name: str, v, typ: str = "uint32_t") -> None:
        a(f"inline constexpr {typ} {name} = {v};")

    a("// ---- Bootstrap registers (§10.3, Table 45) ----")
    for r in m.rows:
        c(const(r.name), f"0x{r.addr:04X}")
    a("")
    a("// ---- Use-case features (§10.3.19-27): bootstrap slot and manufacturer alias ----")
    for d in m.dev:
        c(f"{const(d.name)}_SLOT", f"0x{d.slot:04X}")
        c(f"{const(d.name)}_ALIAS", f"0x{d.alias:X}")
    a("")
    a("// ---- Manufacturer window ----")
    c("MFR_BASE", f"0x{m.mfr_base:X}")
    c("MFR_WORDS", m.mfr_words)
    for w in m.mfr:
        c(const(w.name), f"0x{m.mfr_base + w.off:X}")
    a("")
    a("// ---- Power-on values (a ConnectionReset loads *_CONN_RESET) ----")
    for r in m.kind("RW"):
        c(f"{const(r.name)}_RESET", f"0x{r.reset:X}")
    for d in m.dev:
        c(f"{const(d.name)}_RESET", f"0x{d.reset:X}")
    for w in m.mfr:
        c(f"{const(w.name)}_RESET", f"0x{w.reset:X}")
    for r in m.kind("RO"):
        c(f"{const(r.name)}_VALUE", f"0x{int(r.value):X}")
    a("")
    a("// ---- Strings (NULL-padded to *_LEN bytes on the wire) ----")
    for r in m.kind("STR"):
        c(f"{const(r.name)}_STR", f'"{r.value}"', "const char*")
        c(f"{const(r.name)}_LEN", r.nbytes)
    for r in m.kind("NVSTR"):
        c(f"{const(r.name)}_LEN", r.nbytes)
    a("")
    a("// ---- GenICam XML ROM ----")
    c("XML_BLOB_ADDR", f"0x{m.xml['blob_addr']:08X}")
    c("XML_BLOB_BYTES", m.blob_bytes)
    # The XmlUrl text is XML_URL_STR above; XML_URL is its address.
    c("XML_FILE_NAME", f'"{m.xml["name"]}"', "const char*")
    a("")
    a("// ---- The map as data (regmodel.py in C++) ----")
    a("// A limit that is not there is NONE; `allowed` points at n_allowed values.")
    a("inline constexpr int64_t NONE = -1;")
    a("enum class Kind : uint8_t { RO, RW, CRST, CNT, STR, NVSTR, ZERO };")
    a("")
    a("struct Row {                       // one Table 45 row")
    a("    const char* name;")
    a("    uint32_t addr;")
    a("    Kind kind;")
    a("    uint32_t nbytes;")
    a("    uint32_t value;                 // RO constant")
    a("    const char* text;               // STR text, else nullptr")
    a("    uint32_t reset;                 // RW / CRST power-on value")
    a("    int64_t conn_reset;             // value a ConnectionReset loads, or NONE")
    a("    int64_t min, max;               // refused below / above (0x41), or NONE")
    a("    uint32_t multiple;              // refused unless a multiple of this (0 = any)")
    a("    const uint32_t* allowed;        // refused unless one of these (nullptr = any)")
    a("    uint32_t n_allowed;")
    a("    uint32_t bits;                  // stored bits of an RW row")
    a("};")
    a("")
    a("struct Feature {                   // §10.3.19-27 use-case feature")
    a("    const char* name;")
    a("    uint32_t slot, alias, reset;")
    a("    int64_t min, max;")
    a("    const uint32_t* allowed;")
    a("    uint32_t n_allowed;")
    a("    bool write_only;                // a read is refused (0x44)")
    a("};")
    a("")
    a("struct Word {                      // manufacturer-window word")
    a("    const char* name;")
    a("    uint32_t addr, reset;")
    a("    int64_t min, max;")
    a("    const uint32_t* allowed;")
    a("    uint32_t n_allowed;")
    a("};")
    a("")

    def allowed(name: str, vs) -> str:
        if vs is None:
            return "nullptr, 0"
        a(f"inline constexpr uint32_t {const(name)}_ALLOWED[] = {{"
          + ", ".join(f"0x{v:X}" for v in vs) + "};")
        return f"{const(name)}_ALLOWED, {len(vs)}"

    rows = []
    for r in m.rows:
        al = allowed(r.name, r.allowed)
        val = 0 if r.kind != "RO" else int(r.value)
        txt = f'"{r.value}"' if r.kind == "STR" else "nullptr"
        crs = "NONE" if r.conn_reset is None else f"0x{r.conn_reset:X}"
        rows.append(f'    {{"{r.name}", 0x{r.addr:04X}, Kind::{r.kind}, {r.nbytes}, 0x{val:X}, {txt}, '
                    f"0x{r.reset:X}, {crs}, {_cpp_opt(r.minv)}, {_cpp_opt(r.maxv)}, "
                    f"{r.multiple or 0}, {al}, {r.bits}}},")
    devs = []
    for d in m.dev:
        al = allowed(d.name, d.allowed)
        devs.append(f'    {{"{d.name}", 0x{d.slot:04X}, 0x{d.alias:X}, 0x{d.reset:X}, '
                    f"{_cpp_opt(d.minv)}, {_cpp_opt(d.maxv)}, {al}, {'true' if d.wo else 'false'}}},")
    words = []
    for w in m.mfr:
        al = allowed(w.name, w.allowed)
        words.append(f'    {{"{w.name}", 0x{m.mfr_base + w.off:X}, 0x{w.reset:X}, '
                     f"{_cpp_opt(w.minv)}, {_cpp_opt(w.maxv)}, {al}}},")
    a("")
    a("inline constexpr Row BOOTSTRAP[] = {")
    L.extend(rows)
    a("};")
    a("inline constexpr Feature DEVICE[] = {")
    L.extend(devs)
    a("};")
    a("inline constexpr Word MANUFACTURER[] = {")
    L.extend(words)
    a("};")
    a("")
    a("// A value the register does not take (Table 22 code 0x41).")
    a("constexpr bool refused(uint32_t v, int64_t min, int64_t max, const uint32_t* allowed,")
    a("                       uint32_t n_allowed, uint32_t multiple = 0) {")
    a("    if (min != NONE && int64_t(v) < min) return true;")
    a("    if (max != NONE && int64_t(v) > max) return true;")
    a("    if (multiple && v % multiple) return true;")
    a("    if (!allowed) return false;")
    a("    for (uint32_t i = 0; i < n_allowed; ++i)")
    a("        if (allowed[i] == v) return false;")
    a("    return true;")
    a("}")
    a("")
    a("}  // namespace cxp::reg")
    a("")
    return "\n".join(L)


def _opt(v: Optional[int]) -> str:
    return "None" if v is None else f"0x{v:X}"


def _tup(vs: Optional[List[int]]) -> str:
    return "None" if vs is None else "(" + ", ".join(f"0x{v:X}" for v in vs) + ",)"


def gen_regmodel(m: Map) -> str:
    """The register map as data a reference model can execute.

    `cxp_protocol.regref` turns this into the answer a host should get
    for any read or write — value and Table 22 code — so a testbench can
    check a device's control channel against the map rather than against
    a second hand-written list of addresses.
    """
    L = [f'"""Register map as data for the reference model.  {BANNER}"""',
         "", "from __future__ import annotations", "",
         "# One entry per bootstrap row (Table 45), in address order:",
         "#   name, addr, kind, nbytes, value, reset, conn_reset, max,",
         "#   allowed, bits, min, multiple",
         "# `value` is the constant of an RO row or the text of a STR row;",
         "# `conn_reset` is the value §10.3.28 loads, or None to leave it.",
         "BOOTSTRAP = ("]
    a = L.append
    for r in m.rows:
        val = repr(r.value) if isinstance(r.value, str) else (
            "None" if r.value is None else f"0x{int(r.value):X}")
        crs = "None" if r.conn_reset is None else f"0x{r.conn_reset:X}"
        mx = "None" if r.maxv is None else f"0x{r.maxv:X}"
        al = ("None" if r.allowed is None
              else "(" + ", ".join(f"0x{v:X}" for v in r.allowed) + ",)")
        a(f'    ("{r.name}", 0x{r.addr:04X}, "{r.kind}", {r.nbytes}, {val}, '
          f"0x{r.reset:X}, {crs}, {mx}, {al}, {r.bits}, {_opt(r.minv)}, {_opt(r.multiple)}),")
    a(")")
    a("")
    a("# §10.3.19-27 use-case features: the slot reads the feature's address;")
    a("# the feature is a R/W register at `alias` in the manufacturer window.")
    a("#   name, slot, alias, reset, allowed, min, max, access")
    a("DEVICE = (")
    for d in m.dev:
        a(f'    ("{d.name}", 0x{d.slot:04X}, 0x{d.alias:X}, 0x{d.reset:X}, {_tup(d.allowed)}, '
          f'{_opt(d.minv)}, {_opt(d.maxv)}, "{"WO" if d.wo else "RW"}"),')
    a(")")
    a("")
    a("# Manufacturer-window words that are not feature aliases:")
    a("#   name, addr, reset, min, max, allowed")
    a("MANUFACTURER = (")
    for w in m.mfr:
        a(f'    ("{w.name}", 0x{m.mfr_base + w.off:X}, 0x{w.reset:X}, {_opt(w.minv)}, '
          f'{_opt(w.maxv)}, {_tup(w.allowed)}),')
    a(")")
    a("")
    a(f"MFR_BASE = 0x{m.mfr_base:X}")
    a(f"MFR_WORDS = {m.mfr_words}")
    a(f"XML_BLOB_ADDR = 0x{m.xml['blob_addr']:08X}")
    a(f"XML_BLOB_BYTES = {m.blob_bytes}")
    a(f"XML_URL = {m.xml_url!r}")
    a("")
    return "\n".join(L)


def _takes(x, feat_names: Dict[str, str]) -> str:
    """What a write may set, and the GenICam feature, for the Markdown view."""
    t = []
    if x.entries:
        t.append(", ".join(f"{k} = 0x{v:X}" for k, v in x.entries.items()))
    elif x.allowed is not None:
        t.append(", ".join(f"0x{v:X}" for v in x.allowed))
    if x.minv is not None or x.maxv is not None:
        t.append(f"{x.minv or 0} .. {'—' if x.maxv is None else x.maxv}")
    if getattr(x, "wo", False):
        t.append("write-only (read 0x44)")
    f = feat_names.get(x.name)
    if f:
        t.append(f"XML `{f}`")
    return "; ".join(t)


def gen_md(m: Map) -> str:
    L = ["# cxp_regmap — register map", "", f"_{BANNER}_", "",
         "The register file is `cxp_ctrl_bootstrap_regs`; the decode order and the",
         "ConnectionReset behaviour are described in its header.", "",
         "## Bootstrap registers (Table 45)", "",
         "| Address | Name | Kind | Size | Power-on | ConnectionReset | Notes |",
         "|---|---|---|---|---|---|---|"]
    a = L.append
    for r in m.rows:
        pon = crs = ""
        notes = []
        if r.kind == "RO":
            pon = f"0x{int(r.value):08X}"
        elif r.kind == "RW":
            pon = f"0x{r.reset:X}"
            crs = "" if r.conn_reset is None else f"0x{r.conn_reset:X}"
            if r.max_links:
                notes.append("writes ≥ p_NUM_LINKS: 0x41")
            elif r.maxv is not None:
                notes.append(f"writes > {r.maxv}: 0x41")
            if r.allowed:
                notes.append("takes " + ", ".join(f"0x{v:X}" for v in r.allowed) + "; others 0x41")
            if r.wr_pulse:
                notes.append(f"write pulses `{r.wr_pulse}`")
        elif r.kind == "STR":
            pon = f'"{r.value}"'
        elif r.kind == "CNT":
            notes.append(f"live `{r.inp}`; write 0 pulses its clear")
        elif r.kind == "CRST":
            notes.append("write 1: §10.3.28 reset; self-clears")
        elif r.kind == "NVSTR":
            notes.append(f"power-on from `{r.nv}`")
        elif r.kind == "ZERO":
            notes.append("reads 0")
        if r.out:
            notes.append(f"→ `{r.out}`")
        a(f"| 0x{r.addr:04X} | {r.name} | {r.kind} | {r.nbytes} | {pon} | {crs} | {'; '.join(notes)} |")
    a("")
    a("## Use-case features (§10.3.19-27)")
    a("")
    a("Each 0x3000 slot reads (only) the address of its feature; the feature is a")
    a("R/W register at that manufacturer address.  A ConnectionReset leaves them alone.")
    a("")
    feat = {x.name: x.gc.get("feature", x.name) for x in (*m.rows, *m.dev, *m.mfr) if x.gc}
    a("| Slot | Feature address | Name | Power-on | Takes | Port |")
    a("|---|---|---|---|---|---|")
    for d in m.dev:
        al = f"0x{d.alias:X}" if d.alias else "—"
        port = f"`{d.out}`" + (f", write pulses `{d.wr_pulse}`" if d.wr_pulse else "")
        pon = f"0x{d.reset:04X} (`{d.reset_param}`)" if d.reset_param else f"{d.reset}"
        a(f"| 0x{d.slot:04X} | {al} | {d.name} | {pon} | {_takes(d, feat)} | {port} |")
    a("")
    a(f"## Manufacturer words (0x{m.mfr_base:X} window)")
    a("")
    a("| Address | Name | Power-on | Takes | Port |")
    a("|---|---|---|---|---|")
    for w in m.mfr:
        a(f"| 0x{m.mfr_base + w.off:X} | {w.name} | {w.reset} | {_takes(w, feat)} | "
          f"{('`' + w.out + '`') if w.out else ''} |")
    a("")
    a("## GenICam XML ROM")
    a("")
    a(f"`{m.xml['file']}`, {m.blob_bytes} bytes (0x{m.blob_bytes:X}) at 0x{m.xml['blob_addr']:08X};")
    a(f"XmlUrl = `{m.xml_url}`.")
    a("")
    return "\n".join(L)


