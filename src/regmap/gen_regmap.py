def outputs(m: Map) -> Dict[str, str]:
    return {
        m.xml["file"]: m.xml_bytes.decode("utf-8"),
        OUT_PKG: gen_pkg(m),
        m.xml["mem"]: gen_mem(m),
        OUT_PY: gen_py(m),
        OUT_MODEL: gen_regmodel(m),
        OUT_H: gen_h(m),
        OUT_HPP: gen_hpp(m),
        OUT_MD: gen_md(m),
    }


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true", help="fail if an output is stale")
    args = ap.parse_args()
    m = load()
    stale = 0
    for rel, text in outputs(m).items():
        path = os.path.join(ROOT, rel)
        old = open(path).read() if os.path.exists(path) else None
        if old == text:
            continue
        if args.check:
            stale += 1
            print(f"stale: {rel}")
            sys.stdout.writelines(difflib.unified_diff(
                (old or "").splitlines(True), text.splitlines(True), rel, rel + " (generated)", n=1))
        else:
            with open(path, "w", newline="\n") as f:
                f.write(text)
            print(f"wrote {rel}")
    return 1 if stale else 0


if __name__ == "__main__":
    raise SystemExit(main())
