def gen_pkg(m: Map) -> str:
    L: List[str] = []
    a = L.append
    a("/*")
    a("=" * 80)
    a("  cxp_regmap_pkg")
    a("  CoaXPress 1.1.1 — register map constants (Table 45 + manufacturer space).")
    a("=" * 80)
    a("")
    a(f"    {BANNER}")
    a("")
    a("    Description:")
    a("      Addresses, power-on values and the GenICam XML ROM geometry used by")
    a("      cxp_ctrl_bootstrap_regs, the register router and the benches.  Change")
    a("      src/regmap/cxp_regmap.yaml and run `make regmap` instead of editing.")
    a("")
    a("================================================================*/")
    a("")
    a("`timescale 1ns / 1ns")
    a("")
    a("package cxp_regmap_pkg;")
    a("")
    a("    //=======================================================================")
    a("    // Bootstrap registers (low 16 address bits)")
    a("    //=======================================================================")
    a("")
    for r in m.rows:
        a(f"    localparam logic [15:0] {pad(const(r.name) + '_ADDR', 34)}= {h16(r.addr)};")
    a("")
    a("    //=======================================================================")
    a("    // Use-case feature registers: 0x3000 slot and manufacturer alias")
    a("    //=======================================================================")
    a("")
    for d in m.dev:
        a(f"    localparam logic [15:0] {pad(const(d.name) + '_SLOT', 34)}= {h16(d.slot)};")
        a(f"    localparam logic [31:0] {pad(const(d.name) + '_ALIAS', 34)}= {h32(d.alias)};")
    a("")
    a("    //=======================================================================")
    a("    // Manufacturer window")
    a("    //=======================================================================")
    a("")
    a(f"    localparam logic [31:0] {pad('MFR_BASE', 34)}= {h32(m.mfr_base)};")
    a(f"    localparam int          {pad('MFR_WORDS', 34)}= {m.mfr_words};")
    for w in m.mfr:
        a(f"    localparam logic [31:0] {pad(const(w.name) + '_ADDR', 34)}= {h32(m.mfr_base + w.off)};")
    a("")
    a("    //=======================================================================")
    a("    // Power-on values")
    a("    //=======================================================================")
    a("")
    for r in m.kind("RW"):
        a(f"    localparam logic [31:0] {pad(const(r.name) + '_RESET', 34)}= {h32(r.reset)};")
        if r.conn_reset is not None and r.conn_reset != 0:
            a(f"    localparam logic [31:0] {pad(const(r.name) + '_CONN_RESET', 34)}= {h32(r.conn_reset)};")
    for d in m.dev:
        a(f"    localparam logic [31:0] {pad(const(d.name) + '_RESET', 34)}= {h32(d.reset)};")
    for r in m.kind("RO"):
        a(f"    localparam logic [31:0] {pad(const(r.name) + '_VALUE', 34)}= {h32(int(r.value))};")
    a("")
    a("    //=======================================================================")
    a("    // Read-only strings (NULL-padded to the row length on the wire)")
    a("    //=======================================================================")
    a("")
    for r in m.kind("STR"):
        a(f"    localparam string       {pad(const(r.name) + '_STR', 34)}= \"{r.value}\";")
    a("")
    a("    //=======================================================================")
    a("    // Address windows seen by the register router")
    a("    //=======================================================================")
    a("")
    boot_end = max(r.addr + ((r.nbytes + 3) // 4) * 4 for r in m.rows if r.addr < m.xml["url_addr"])
    a("    // Last byte of the bootstrap block the router forwards (0x40FF: the")
    a("    // Table 45 CXP group rounded up to its 256-byte page).")
    a(f"    localparam logic [31:0] {pad('BOOTSTRAP_END', 34)}= {h32((boot_end | 0xFF))};")
    a("")
    a("    //=======================================================================")
    a("    // GenICam XML ROM")
    a("    //=======================================================================")
    a("")
    a(f"    localparam logic [31:0] {pad('XML_BLOB_ADDR', 34)}= {h32(m.xml['blob_addr'])};")
    a(f"    localparam logic [31:0] {pad('XML_BLOB_BYTES', 34)}= {h32(m.blob_bytes)};   // {m.blob_bytes}")
    a(f"    localparam int          {pad('XML_BLOB_WORDS', 34)}= {m.blob_words};")
    a(f"    localparam string       {pad('XML_BLOB_MEM', 34)}= \"{os.path.basename(m.xml['mem'])}\";")
    a("")
    a("endpackage")
    a("")
    return "\n".join(L)


