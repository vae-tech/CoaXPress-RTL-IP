# GenICam XML (GenApi schema 1.1)
# =============================================================================
GENAPI_NS = "http://www.genicam.org/GenApi/Version_1_1"
GENAPI_XSD = "http://www.genicam.org/GenApi/GenApiSchema_Version_1_1.xsd"
GC_KEYS = {"feature", "type", "category", "description", "tooltip", "display", "visibility",
           "representation", "unit", "streamable", "namespace", "selects", "nocache"}
GC_TYPES = ("Integer", "Enumeration", "Command", "String", "Boolean")


def _int_limits(name: str, minv, maxv, allowed, multiple, nbytes: int):
    """(Min, Max, Inc) of an Integer feature: what the register takes."""
    if allowed is not None:
        vs = sorted(allowed)
        if vs != list(range(vs[0], vs[-1] + 1)):
            raise SystemExit(f"{name}: an Integer's `allowed` must be a range; "
                             "name the values (a mapping) to make it an Enumeration")
        return vs[0], vs[-1], None
    if minv is None and maxv is None and not multiple:
        return None, None, None
    top = (1 << (8 * nbytes)) - 1
    if maxv is None and multiple:
        maxv = top // multiple * multiple
    return (minv or 0), maxv, multiple


def features(m: Map) -> List[Feat]:
    """Every row with `gc:` as a feature, in map order."""
    out: List[Feat] = []

    def add(x, addr: int, nbytes: int, access: str, kind: str, ns: str, multiple=None) -> None:
        gc = dict(x.gc)
        bad = set(gc) - GC_KEYS
        if bad:
            raise SystemExit(f"{x.name}: unknown gc key(s) {sorted(bad)}")
        if kind in ("STR", "NVSTR"):
            typ = "String"
        elif access == "WO":
            typ = "Command"
        elif x.entries:
            typ = "Enumeration"
        else:
            typ = "Integer"
        typ = gc.get("type", typ)
        if typ not in GC_TYPES:
            raise SystemExit(f"{x.name}: gc.type {typ} is not one of {GC_TYPES}")
        if typ == "Enumeration" and not x.entries:
            raise SystemExit(f"{x.name}: an Enumeration needs `allowed` as a name -> value mapping")
        f = Feat(name=gc.get("feature", x.name), type=typ, ns=gc.get("namespace", ns), gc=gc,
                 addr=addr, length=nbytes, access=access, entries=x.entries)
        if typ in ("Integer", "Boolean"):
            f.minv, f.maxv, f.inc = _int_limits(x.name, x.minv, x.maxv, x.allowed, multiple, nbytes)
        out.append(f)

    for r in m.rows:
        if r.gc is None:
            continue
        if r.kind not in ("RO", "RW", "CNT", "STR", "NVSTR"):
            raise SystemExit(f"{r.name}: a {r.kind} row cannot be a GenICam feature")
        acc = "RO" if r.kind in ("RO", "STR") else "RW"
        add(r, r.addr, r.nbytes, acc, r.kind, "Standard", r.multiple)
    for d in m.dev:
        if d.gc is not None:
            add(d, d.alias, 4, "WO" if d.wo else "RW", "RW", "Standard")
    for w in m.mfr:
        if w.gc is not None:
            add(w, m.mfr_base + w.off, 4, "RW", "RW", "Custom")
    names = [f.name for f in out]
    dup = {n for n in names if names.count(n) > 1}
    if dup:
        raise SystemExit(f"GenICam feature name(s) used twice: {sorted(dup)}")
    return out


def _x(s) -> str:
    return xml_escape(" ".join(str(s).split()))


def _num(v: int) -> str:
    return str(v) if v < 0x100 else f"0x{v:04X}"


def _addr(v: int) -> str:
    return f"0x{v:04X}"


def gen_xml(m: Map) -> str:
    """The GenICam description of the device, GenApi schema 1.1."""
    g = m.gc
    feats = features(m)
    cats = g["categories"]
    cat_names = [c["name"] for c in cats]
    for f in feats:
        if f.gc.get("category") not in cat_names:
            raise SystemExit(f"{f.name}: gc.category {f.gc.get('category')!r} is not in genicam.categories")
    port = g["port"]
    L: List[str] = []
    a = L.append
    ver, sch = g["version"], g["schema"]
    a('<?xml version="1.0" encoding="UTF-8"?>')
    a("<!--")
    a(f"  {BANNER.replace(' -- ', '; ')}")              # no "--" in an XML comment
    a("  GenICam description of the CoaXPress 1.1.1 device IP (GenApi schema")
    a(f"  {sch['major']}.{sch['minor']}.{sch.get('subminor', 0)}), served from the XML ROM at "
      f"0x{m.xml['blob_addr']:08X}; XmlUrl at 0x{m.xml['url_addr']:04X}.")
    a("-->")
    a("<RegisterDescription")
    a(f'    ModelName="{_x(g["model"])}"')
    a(f'    VendorName="{_x(g["vendor"])}"')
    a(f'    ToolTip="{_x(g["tooltip"])}"')
    a(f'    StandardNameSpace="{g["standard_namespace"]}"')
    a(f'    SchemaMajorVersion="{sch["major"]}" SchemaMinorVersion="{sch["minor"]}" '
      f'SchemaSubMinorVersion="{sch.get("subminor", 0)}"')
    a(f'    MajorVersion="{ver["major"]}" MinorVersion="{ver["minor"]}" '
      f'SubMinorVersion="{ver.get("subminor", 0)}"')
    a(f'    ProductGuid="{g["product_guid"]}"')
    a('    VersionGuid="@VERSION_GUID@"')
    a(f'    xmlns="{GENAPI_NS}"')
    a('    xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance"')
    a(f'    xsi:schemaLocation="{GENAPI_NS} {GENAPI_XSD}">')

    def common(gc: dict) -> None:
        # ToolTip, Description, DisplayName, Visibility: the schema's order.
        for key, tag in (("tooltip", "ToolTip"), ("description", "Description"),
                         ("display", "DisplayName"), ("visibility", "Visibility")):
            if gc.get(key):
                a(f"    <{tag}>{_x(gc[key])}</{tag}>")

    for c in cats:
        bad = set(c) - {"name", "description", "tooltip", "display", "visibility",
                        "namespace", "children"}
        if bad:
            raise SystemExit(f"category {c['name']}: unknown key(s) {sorted(bad)}")
        a("")
        a(f'  <Category Name="{c["name"]}" NameSpace="{c.get("namespace", "Standard")}">')
        common(c)
        for f in feats:
            if f.gc["category"] == c["name"]:
                a(f"    <pFeature>{f.name}</pFeature>")
        for k in c.get("children", []):
            if k not in cat_names:
                raise SystemExit(f"category {c['name']}: child {k} is not a category")
            a(f"    <pFeature>{k}</pFeature>")
        a("  </Category>")

    for c in cats:
        for f in feats:
            if f.gc["category"] != c["name"]:
                continue
            gc = f.gc
            a("")
            a(f'  <{f.type} Name="{f.name}" NameSpace="{f.ns}">')
            common(gc)
            if "streamable" in gc:
                a(f"    <Streamable>{'Yes' if gc['streamable'] else 'No'}</Streamable>")
            if f.type == "Enumeration":
                for en, ev in f.entries.items():
                    a(f'    <EnumEntry Name="{en}"><Value>{_num(ev)}</Value></EnumEntry>')
            a(f"    <pValue>{f.reg}</pValue>")
            if f.type == "Command":
                a("    <CommandValue>1</CommandValue>")       # §11.2.1.4-5: single-shot 1
            if f.type == "Integer":
                lim = _num if gc.get("representation") == "HexNumber" else str
                if f.minv is not None:
                    a(f"    <Min>{lim(f.minv)}</Min>")
                if f.maxv is not None:
                    a(f"    <Max>{lim(f.maxv)}</Max>")
                if f.inc:
                    a(f"    <Inc>{f.inc}</Inc>")
                if gc.get("representation"):
                    a(f"    <Representation>{gc['representation']}</Representation>")
                if gc.get("unit"):
                    a(f"    <Unit>{_x(gc['unit'])}</Unit>")
                for s in gc.get("selects", []):
                    a(f"    <pSelected>{s}</pSelected>")
            elif f.type == "Boolean":
                a("    <OnValue>1</OnValue>")
                a("    <OffValue>0</OffValue>")
            a(f"  </{f.type}>")
            tag = "StringReg" if f.type == "String" else "IntReg"
            a(f'  <{tag} Name="{f.reg}">')
            a(f"    <Address>{_addr(f.addr)}</Address><Length>{f.length}</Length>"
              f"<AccessMode>{f.access}</AccessMode>")
            tail = f"<pPort>{port}</pPort>"
            if gc.get("nocache"):
                tail += "<Cachable>NoCache</Cachable>"
            if tag == "IntReg":                               # §10.3.3: big-endian
                tail += "<Sign>Unsigned</Sign><Endianess>BigEndian</Endianess>"
            a(f"    {tail}")
            a(f"  </{tag}>")

    a("")
    a(f'  <Port Name="{port}" NameSpace="Standard"/>')
    a("")
    a("</RegisterDescription>")
    a("")
    text = "\n".join(L)
    # The VersionGuid names this exact file: a UUIDv5 of its content.
    vg = uuid.uuid5(uuid.UUID(g["product_guid"]), text)
    return text.replace("@VERSION_GUID@", str(vg))


def _xml_selfcheck(m: Map, text: str) -> None:
    """Structural check of the generated tree: every node reference
    resolves, every feature hangs under Root, every register node is a
    register of the map with the map's access mode."""
    root = ET.fromstring(text)
    nodes = {}
    for el in root:
        tag = el.tag.split("}", 1)[-1]
        nodes[el.get("Name")] = (tag, el)
    q = lambda el, t: el.findall(f"{{{GENAPI_NS}}}{t}")
    for name, (tag, el) in nodes.items():
        for t in ("pFeature", "pValue", "pPort", "pSelected"):
            for ref in q(el, t):
                if ref.text not in nodes:
                    raise SystemExit(f"XML {name}: <{t}>{ref.text}</{t}> names no node")
    reached, todo = set(), ["Root"]
    while todo:
        n = todo.pop()
        reached.add(n)
        todo += [p.text for p in q(nodes[n][1], "pFeature") if p.text not in reached]
    decoded = set()
    for r in m.rows:
        decoded.update(range(r.addr, r.addr + r.nbytes, 4))
    decoded.update(d.alias for d in m.dev)
    decoded.update(m.mfr_base + w.off for w in m.mfr)
    for name, (tag, el) in nodes.items():
        if tag in ("IntReg", "StringReg"):
            a = int(q(el, "Address")[0].text, 0)
            if a not in decoded:
                raise SystemExit(f"XML {name}: address 0x{a:X} is not a register of the map")
        elif tag not in ("Category", "Port") and name not in reached:
            raise SystemExit(f"XML {name}: not under Root")


