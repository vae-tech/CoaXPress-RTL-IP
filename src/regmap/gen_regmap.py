    a("# GenICam XML ROM")
    a(f"XML_BLOB_ADDR = 0x{m.xml['blob_addr']:08X}")
    a(f"XML_BLOB_BYTES = {m.blob_bytes}")
    up = ", ".join(['".."'] * (OUT_PY.count("/")))
    a("")
