# Helpers
# =============================================================================
def const(name: str) -> str:
    """CamelCase register name -> UPPER_SNAKE constant stem."""
    out = []
    for i, c in enumerate(name):
        if c.isupper() and i and (not name[i - 1].isupper()
                                  or (i + 1 < len(name) and name[i + 1].islower())):
            out.append("_")
        out.append(c.upper())
    return "".join(out).replace("__", "_")


def h32(v: int) -> str:
    return f"32'h{v >> 16:04X}_{v & 0xFFFF:04X}"


def h16(v: int) -> str:
    return f"16'h{v:04X}"


def sv_str(s: str, nbytes: int) -> str:
    """Big-endian, NULL-padded string literal of exactly nbytes bytes."""
    pad = nbytes - len(s)
    body = f'"{s}"' if s else ""
    if pad and body:
        return "{" + body + f", {{{pad}{{8'h00}}}}" + "}"
    if pad:
        return f"{{{pad}{{8'h00}}}}"
    return body


def pad(s: str, n: int) -> str:
    return s + " " * max(1, n - len(s))


